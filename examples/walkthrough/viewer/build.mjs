import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = new URL('.', import.meta.url), output = new URL('dist/', root);
await mkdir(output, {recursive: true});
await build({entryPoints: [fileURLToPath(new URL('viewer.js', root))], outfile: fileURLToPath(new URL('viewer.js', output)), bundle: true, format: 'esm', minify: true, target: 'es2022', legalComments: 'linked'});
for (const name of ['viewer.html', 'SPECKLE-LICENSE']) await copyFile(new URL(name, root), new URL(name, output));
const files = {}, sources = {};
for (const name of ['viewer.js', 'viewer.js.LEGAL.txt', 'viewer.html', 'SPECKLE-LICENSE']) files[name] = createHash('sha256').update(await readFile(new URL(name, output))).digest('hex');
for (const name of ['viewer.js','viewer.html','build.mjs','package.json','package-lock.json','SPECKLE-LICENSE']) sources[name] = createHash('sha256').update(await readFile(new URL(name, root))).digest('hex');
await writeFile(new URL('manifest.json', output), JSON.stringify({format: 'rangekeeper.local-geometry/v1', version: '0.1.0', files, sources}, null, 2) + '\n');
