"""Generate the shared record boundary. Run with the pinned requirements.txt.

--check compares artifacts without changing the checkout. No runtime imports of
LinkML are required by the immutable records or their packaged validators.
--native PATH writes the stock LinkML Python module out of tree, for the
conformance tools; the package does not contain it.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import importlib.metadata
import json
import keyword
import pprint
import re
import tempfile
from pathlib import Path
from typing import NamedTuple

import yaml
from jsonschema import Draft202012Validator
from linkml.generators.jsonschemagen import JsonSchemaGenerator
from linkml.generators.pythongen import PythonGenerator
from linkml_runtime.utils.schemaview import SchemaView

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / "src/rangekeeper/schema"
PINNED = {
    "linkml": "1.11.1",
    "linkml-runtime": "1.11.1",
    "jsonschema": "4.26.0",
    "PyYAML": "6.0.3",
}
# The owner package of each value type (ADR-011). The owner subclasses the
# generated record and registers it in rangekeeper.schema.kinds; records decode
# to the owner class. The records name owners only for type checking.
OWNERS = {
    "Distribution": "rangekeeper.profile",
    "Flow": "rangekeeper.flow",
    "Movement": "rangekeeper.flow",
    "Period": "rangekeeper.duration",
    "Span": "rangekeeper.duration",
}
# Members that records.py adds to every class besides its fields.
GENERATED = {"replace", "_kind"}
PRIMITIVES = {
    "string": "str",
    "Code": "str",
    "URI": "str",
    "integer": "int",
    "decimal": "int | float",
    "double": "int | float",
    "float": "int | float",
    "boolean": "bool",
    "date": "Date",
    "datetime": "str",
}
# Boolean LinkML slot annotations that slots.json carries for every slot. A
# lineage slot records document revision identity or lineage: it is not domain
# content in a revision comparison and not a reference to a record in the
# document.
ANNOTATIONS = ("lineage",)


def encoded(value):
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def enum_member(value):
    """Derive one stable Python identifier without masking naming collisions."""
    name = re.sub(r"[^A-Za-z0-9_]", "_", value).upper()
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError(f"Invalid enum member name for {value!r}")
    return name


def enum_source(enums):
    lines = [
        "# Generated by tools/schema/generate.py; do not edit.",
        "from enum import Enum, unique",
        "",
    ]
    for name, declaration in sorted(enums.items()):
        members = [
            (enum_member(value), value) for value in declaration.permissible_values
        ]
        if len({member for member, _ in members}) != len(members):
            raise ValueError(f"Colliding enum member names in {name}")
        lines.extend(["@unique", f"class {name}(Enum):"])
        lines.extend(f"    {member} = {value!r}" for member, value in members)
        lines.append("")
    lines.extend(
        [
            "_ENUM_TYPES = {",
            *[f"    {name!r}: {name}," for name in sorted(enums)],
            "}",
            "",
            "__all__ = " + repr(sorted(enums)),
            "",
        ]
    )
    return "\n".join(lines)


def simplify_conjunctions(node):
    """Remove A-or-B when the same schema node already requires A.

    LinkML can emit a recursive $ref both directly and in anyOf. Rechecking
    both at each Expression level makes validation exponential in tree depth.
    A AND (A OR B) is exactly A, including for null and invalid input. No
    field, constraint or accepted wire shape is added by this transformation.
    """
    if isinstance(node, list):
        for child in node:
            simplify_conjunctions(child)
    elif isinstance(node, dict):
        for child in node.values():
            simplify_conjunctions(child)
        required = list(node.get("allOf", []))
        if "$ref" in node:
            required.append({"$ref": node["$ref"]})
        if any(item in node.get("anyOf", []) for item in required):
            del node["anyOf"]


def check_dependencies():
    """Return the installed generator versions; stop when they differ from PINNED."""
    versions = {name: importlib.metadata.version(name) for name in PINNED}
    if versions != PINNED:
        raise SystemExit(f"Use tools/schema/requirements.txt; observed {versions}")
    return versions


def read_sources():
    """Return the bytes of every input that the manifest fingerprints."""
    sources = {
        f"schema/{p.name}": p.read_bytes()
        for p in sorted((ROOT / "schema").glob("*.yaml"))
    }
    sources["tools/schema/bundle.yaml"] = (
        Path(__file__).with_name("bundle.yaml").read_bytes()
    )
    sources["tools/schema/generate.py"] = Path(__file__).read_bytes()
    sources["tools/schema/requirements.txt"] = (
        Path(__file__).with_name("requirements.txt").read_bytes()
    )
    return sources


class Loaded(NamedTuple):
    """The resolved LinkML bundle and its derived JSON Schema."""

    view: SchemaView
    classes: dict
    enums: dict
    shared: dict
    opaque: frozenset
    native: str


def load(directory: Path, sources) -> Loaded:
    """Resolve the schema imports into one bundle in a temporary directory."""
    for name, value in sources.items():
        if name.startswith("schema/"):
            (directory / Path(name).name).write_bytes(value)
    bundle = directory / "bundle.yaml"
    bundle.write_bytes(sources["tools/schema/bundle.yaml"])
    view = SchemaView(str(bundle))
    classes = view.all_classes()
    enums = view.all_enums()
    schema = json.loads(
        JsonSchemaGenerator(
            str(bundle), top_class="Model", not_closed=False
        ).serialize()
    )
    # Every root uses the same complete definitions; no inferred tree-root choice.
    shared = {
        "$schema": schema["$schema"],
        "$id": schema["$id"],
        "$defs": schema["$defs"],
    }
    simplify_conjunctions(shared)
    Draft202012Validator.check_schema(shared)
    opaque = frozenset(
        name
        for name, cls in classes.items()
        if str(cls.class_uri) in ("linkml:Any", "https://w3id.org/linkml/Any")
    )
    native = PythonGenerator(str(bundle), metadata=False).serialize()
    if str(directory) in native or str(directory) in encoded(shared):
        raise ValueError("Generator leaked temporary source path")
    return Loaded(view, classes, enums, shared, opaque, native)


def slot_options(loaded: Loaded, field):
    """Return the distinct wire options of one induced slot."""
    options = []
    for variant in field.any_of or [field]:
        kind = variant.range or field.range or "string"
        inline = variant.inlined if variant.inlined is not None else field.inlined
        inline = bool(inline or variant.inlined_as_list or field.inlined_as_list)
        if kind in loaded.opaque:
            category = "opaque"
        elif kind == "UUID" or kind in loaded.classes and not inline:
            category = "uuid"
        elif kind in loaded.classes:
            category = "record"
        elif kind in loaded.enums:
            category = "enum"
        else:
            category = "primitive"
        option = {"kind": kind, "category": category}
        if option not in options:
            options.append(option)
    return options


def keyed_options(name, field, prop):
    """Return the options of a keyed collection from its JSON Schema values.

    LinkML keyed collections may use reduced dictionaries or scalar values.
    Preserve both wire forms rather than inventing Entry IDs.
    """
    options = []
    for variant in prop["additionalProperties"].get("anyOf", []):
        if "$ref" in variant:
            options.append({"kind": field.range, "category": "keyed"})
        elif "type" in variant:
            options.append({"kind": variant["type"], "category": "primitive"})
        else:
            raise ValueError(f"Unsupported keyed collection: {name}.{field.name}")
    if not options:
        raise ValueError(f"Unsupported keyed collection: {name}.{field.name}")
    return options


def slot_annotations(name, field):
    """Return the boolean annotations of one induced slot; reject other annotations."""
    # SchemaView returns induced annotations as a JsonObj, not as a dict.
    annotations = field.annotations
    items = annotations._items() if hasattr(annotations, "_items") else annotations
    found = {tag: annotation.value for tag, annotation in dict(items).items()}
    unknown = sorted(set(found) - set(ANNOTATIONS))
    if unknown:
        raise ValueError(f"Unsupported slot annotation {unknown}: {name}.{field.name}")
    for tag, value in found.items():
        if not isinstance(value, bool):
            raise ValueError(
                f"Slot annotation {tag} is not boolean: {name}.{field.name}"
            )
    return {tag: found.get(tag, False) for tag in ANNOTATIONS}


def class_slots(loaded: Loaded, name):
    """Return the slot metadata of one class, in induced order."""
    result = {}
    for field in loaded.view.class_induced_slots(name):
        prop = loaded.shared["$defs"][name].get("properties", {}).get(field.name, {})
        mapping = bool(field.multivalued and "additionalProperties" in prop)
        options = (
            keyed_options(name, field, prop) if mapping else slot_options(loaded, field)
        )
        nullable = Draft202012Validator({**loaded.shared, **prop}).is_valid(None)
        result[field.name] = dict(
            options=options,
            required=bool(field.required),
            many=bool(field.multivalued),
            mapping=mapping,
            nullable=nullable,
            ordered=bool(field.list_elements_ordered),
            **slot_annotations(name, field),
        )
    return result


def slots(loaded: Loaded):
    """Return the slot metadata of every class."""
    return {name: class_slots(loaded, name) for name in sorted(loaded.classes)}


def reserved_names():
    """Return the attribute names of Record that a generated field must not shadow.

    The names come from the source of the record runtime, so the generator does
    not import the package. The kind registry checks owner subclasses.
    """
    source = (ROOT / "src/rangekeeper/schema/runtime.py").read_text()
    for node in ast.parse(source).body:
        if isinstance(node, ast.ClassDef) and node.name == "Record":
            return {name for child in node.body for name in _defined_names(child)}
    raise ValueError("runtime.py defines no Record class")


def _defined_names(node):
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return {node.name}
    if isinstance(node, ast.Assign):
        return {t.id for t in node.targets if isinstance(t, ast.Name)}
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return {node.target.id}
    return set()


def check_slots(slots, reserved):
    """Reject slot names and shapes that the generated records cannot represent.

    - A slot name must be a Python identifier that is not a keyword.
    - A slot name must not shadow a method or attribute of Record or a
      generated method.
    - A slot has at most one inlined record type, so decoding is not ambiguous.
    - An enum slot has one option and is not a collection.
    """
    record = reserved | GENERATED
    for name, fields in slots.items():
        for field, meta in fields.items():
            label = f"{name}.{field}"
            if not field.isidentifier() or keyword.iskeyword(field):
                raise ValueError(f"Slot name is not a Python identifier: {label}")
            if field in record:
                raise ValueError(f"Slot name shadows a record method: {label}")
            categories = [option["category"] for option in meta["options"]]
            if categories.count("record") + categories.count("keyed") > 1:
                raise ValueError(f"Slot has more than one record type: {label}")
            if "enum" in categories and (
                len(categories) != 1 or meta["mapping"] or meta["many"]
            ):
                raise ValueError(f"Unsupported enum slot shape: {name}.{field}")


def descriptions(loaded: Loaded):
    """Return the LinkML description of every class and of each of its slots."""
    return {
        name: dict(
            description=loaded.classes[name].description,
            slots={
                field.name: field.description
                for field in loaded.view.class_induced_slots(name)
            },
        )
        for name in sorted(loaded.classes)
    }


def check_descriptions(descriptions):
    """Reject a class or slot without a description.

    The descriptions become the record and property docstrings, so the
    generator does not write a placeholder in their place.
    """
    missing = []
    for name, described in descriptions.items():
        if not str(described["description"] or "").strip():
            missing.append(name)
        missing += [
            f"{name}.{field}"
            for field, text in described["slots"].items()
            if not str(text or "").strip()
        ]
    if missing:
        raise ValueError("Missing LinkML descriptions: " + ", ".join(missing))


def field_type(meta, argument=False):
    """Return the Python annotation of one field, as an argument or a property."""
    variants = []
    for option in meta["options"]:
        kind, category = option["kind"], option["category"]
        if category == "uuid":
            typ = "UUID"
        elif category == "opaque":
            typ = "JSONValue" if argument else "FrozenJSONValue"
        elif category == "keyed":
            typ = (
                "Mapping[str, JSONValue]"
                if argument
                else "Mapping[str, FrozenJSONValue]"
            )
        elif category == "record" and kind in OWNERS and not argument:
            typ = f"_{kind}"
        elif category in ("record", "enum"):
            typ = kind
        else:
            typ = PRIMITIVES.get(kind)
            if typ is None:
                raise ValueError(f"Unsupported primitive {kind}")
        if typ not in variants:
            variants.append(typ)
    typ = " | ".join(variants)
    if meta["mapping"]:
        typ = f"Mapping[str, {typ}]"
    elif meta["many"]:
        typ = f"tuple[{typ}, ...]"
    if meta["nullable"] or not argument and not meta["required"] and not meta["many"]:
        typ += " | None"
    if argument and not meta["required"]:
        typ += " | Unset"
    return typ


def record_header(loaded: Loaded):
    """Return the imports and aliases at the top of records.py."""
    lines = [
        "# Generated by tools/schema/generate.py; do not edit.",
        "from __future__ import annotations",
        "",
        "from typing import TYPE_CHECKING, Self, cast",
        "from collections.abc import Mapping",
        "from uuid import UUID",
        "from datetime import date as Date",
        "from .runtime import (",
        "    EMPTY,",
        "    UNSET,",
        "    FrozenJSONValue,",
        "    JSONValue,",
        "    Record,",
        "    Unset,",
        "    _decode_date,",
        "    _decode_dates,",
        "    _decode_enum,",
        "    _decode_uuid,",
        "    _decode_uuids,",
        "    _encode_date,",
        "    _encode_enum,",
        "    _encode_many,",
        "    _encode_record,",
        "    _encode_uuid,",
        "    _freeze,",
        "    copy_json,",
        ")",
        "",
        "if TYPE_CHECKING:",
        *[
            f"    from {module} import {kind} as _{kind}"
            for kind, module in sorted(OWNERS.items())
        ],
        "",
    ]
    lines += [f"from .enums import {name} as {name}" for name in sorted(loaded.enums)]
    lines += [f"{name} = FrozenJSONValue" for name in sorted(loaded.opaque)]
    lines += [""]
    return lines


def record_class(loaded: Loaded, name, fields):
    """Return the source lines of one record class."""
    parent = loaded.classes[name].is_a
    bases = [str(parent or "Record")]
    lines = [
        f"class {name}({', '.join(bases)}):",
        f"    {str(loaded.classes[name].description)!r}",
        "    __slots__ = ()",
        f"    _kind = {name!r}",
        "    _SLOTS = _freeze(",
        *[
            "        " + line
            for line in pprint.pformat(fields, width=80, sort_dicts=False).splitlines()
        ],
        "    )",
        "",
    ]
    lines += record_init(fields)
    lines += record_replace(name, fields)
    lines += record_properties(loaded, name, fields)
    lines.append("")
    return lines


def encoder(meta):
    """Return the expression that encodes the typed value ``v`` of one field.

    The generator selects the encoder of each field; the runtime does not read
    slot metadata to construct a record. A union field uses the general encoder.
    """
    options = meta["options"]
    if meta["mapping"] or len(options) != 1:
        return None
    category, kind = options[0]["category"], options[0]["kind"]
    if category == "uuid":
        return "_encode_uuid({})"
    if category == "enum":
        return f"_encode_enum({{}}, {kind}, NAME)"
    if category == "record":
        return f"_encode_record({{}}, {kind}, NAME)"
    if category == "primitive" and kind == "date":
        return "_encode_date({})"
    return "copy_json({})"


def encode_lines(fields, target, *, constructor):
    """Return the lines that encode each supplied field into ``target``.

    A required constructor argument is always supplied; every other argument
    may be UNSET, which leaves the field out.
    """
    lines = []
    for field, meta in fields.items():
        expression = encoder(meta)
        if expression is None:
            value = f"self._encode_field({field!r}, {field})"
        else:
            expression = expression.replace("NAME", repr(field))
            value = (
                f"_encode_many({field}, lambda v: {expression.format('v')})"
                if meta["many"]
                else expression.format(field)
            )
        if constructor and meta["required"]:
            lines.append(f"        {target}[{field!r}] = {value}")
        else:
            lines += [
                f"        if {field} is not UNSET:",
                f"            {target}[{field!r}] = {value}",
            ]
    return lines


def record_init(fields):
    """Return the keyword-only constructor of one record class."""
    args = [
        f"        {field}: {field_type(meta, True)}"
        + ("" if meta["required"] else " = UNSET")
        + ","
        for field, meta in fields.items()
    ]
    return [
        "    def __init__(self, *,",
        *args,
        "    ) -> None:",
        "        data: dict[str, object] = {}",
        *encode_lines(fields, "data", constructor=True),
        "        self._set_data(data)",
        "",
    ]


def record_replace(name, fields):
    """Return the typed replace method of one record class.

    Replacement uses the same field encoders and structural validation as
    construction. UNSET preserves the existing field's presence and value.
    """
    lines = ["    def replace(self, *,"]
    for field, meta in fields.items():
        typ = field_type(meta, True)
        if "Unset" not in typ:
            typ += " | Unset"
        lines.append(f"        {field}: {typ} = UNSET,")
    return lines + [
        "    ) -> Self:",
        '        """Return a validated copy; omitted arguments preserve field presence and value."""',
        "        changes: dict[str, object] = {}",
        *encode_lines(fields, "changes", constructor=False),
        "        return self._replace(changes)",
        "",
    ]


def decoder(field, meta):
    """Return the expression that decodes one field from ``self._data``.

    A missing collection reads as empty and a missing single value as None.
    Records decode once and stay in the child cache. A union field uses the
    general decoder.
    """
    options = meta["options"]
    name = repr(field)
    if meta["mapping"]:
        return f"self._data.get({name}, EMPTY)"
    if len(options) != 1:
        return f"self._field({name})"
    category, kind = options[0]["category"], options[0]["kind"]
    many = meta["many"]
    if category == "record":
        return f"self._child({name}, {kind}, {many})"
    if category == "uuid":
        return (
            f"_decode_uuids(self._data.get({name}, ()))"
            if many
            else (f"_decode_uuid(self._data.get({name}))")
        )
    if category == "enum":
        return f"_decode_enum(self._data.get({name}), {kind})"
    if category == "primitive" and kind == "date":
        return (
            f"_decode_dates(self._data.get({name}, ()))"
            if many
            else (f"_decode_date(self._data.get({name}))")
        )
    return f"self._data.get({name}, ())" if many else f"self._data.get({name})"


def record_properties(loaded: Loaded, name, fields):
    """Return one read-only property for each field of one record class."""
    texts = {
        field.name: field.description for field in loaded.view.class_induced_slots(name)
    }
    lines = []
    for field, meta in fields.items():
        typ = field_type(meta)
        value = decoder(field, meta)
        # An opaque field reads its frozen value directly; a cast would be redundant.
        if typ != "FrozenJSONValue | None":
            value = f"cast({typ!r}, {value})"
        lines += [
            "    @property",
            f"    def {field}(self) -> {typ}:",
            f"        {str(texts[field])!r}",
            f"        return {value}",
            "",
        ]
    return lines


def records_source(loaded: Loaded, slots):
    """Return records.py, with each parent class before its children."""
    lines = record_header(loaded)
    done = set(loaded.opaque)

    def emit(name):
        if name in done:
            return
        parent = loaded.classes[name].is_a
        if parent:
            emit(str(parent))
        lines.extend(record_class(loaded, name, slots[name]))
        done.add(name)

    for name in sorted(loaded.classes):
        emit(name)
    lines += [
        "_TYPES = {",
        *[f"    {n!r}: {n}," for n in sorted(loaded.classes) if n not in loaded.opaque],
        "}",
        "",
        "_SLOTS = {",
        *[
            f"    {n!r}: {n}._SLOTS,"
            for n in sorted(loaded.classes)
            if n not in loaded.opaque
        ],
        "}",
        "",
        "_OWNERS = {",
        *[f"    {kind!r}: {module!r}," for kind, module in sorted(OWNERS.items())],
        "}",
        "",
        "__all__ = " + repr(sorted(set(loaded.classes) | set(loaded.enums))),
        "",
    ]
    return "\n".join(lines)


def manifest(loaded: Loaded, versions, sources, files):
    """Return the manifest of dependencies, source and artifact hashes, and versions."""
    return {
        "generator_version": 1,
        "dependencies": versions,
        "sources": {
            name: hashlib.sha256(data).hexdigest() for name, data in sources.items()
        },
        "document_versions": {
            kind: yaml.safe_load(sources[f"schema/{kind.lower()}.yaml"])["version"]
            for kind in ("Model", "Specification", "Run")
        },
        "classes": sorted(loaded.classes),
        "opaque_classes": sorted(loaded.opaque),
        "artifacts": {
            name: hashlib.sha256(data.encode()).hexdigest()
            for name, data in files.items()
        },
    }


def generate(*, native_module: bool = False):
    """Return the packaged artifacts, plus native.py when native_module is set."""
    versions = check_dependencies()
    sources = read_sources()
    with tempfile.TemporaryDirectory(prefix="rk-generate-") as directory:
        loaded = load(Path(directory), sources)
    metadata = slots(loaded)
    check_slots(metadata, reserved_names())
    check_descriptions(descriptions(loaded))
    files = {
        "enums.py": enum_source(loaded.enums),
        "records.py": records_source(loaded, metadata),
        "schema.json": encoded(loaded.shared),
        "slots.json": encoded(metadata),
    }
    files["manifest.json"] = encoded(manifest(loaded, versions, sources, files))
    if native_module:
        files["native.py"] = loaded.native
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=DESTINATION)
    parser.add_argument("--native", type=Path, help="write the stock LinkML module")
    args = parser.parse_args()
    if args.native:
        args.native.write_text(generate(native_module=True)["native.py"])
        print(f"Generated stock LinkML module {args.native}")
        return
    files = generate()
    changed = [
        name
        for name, data in files.items()
        if not (args.output / name).exists() or (args.output / name).read_text() != data
    ]
    if args.check:
        if changed:
            raise SystemExit("Generated artifacts differ: " + ", ".join(changed))
    else:
        args.output.mkdir(parents=True, exist_ok=True)
        for name, data in files.items():
            (args.output / name).write_text(data)
    print(
        f"{'Verified' if args.check else 'Generated'} {len(files)} artifacts, "
        f"{len(json.loads(files['manifest.json'])['classes'])} schema classes"
    )


if __name__ == "__main__":
    main()
