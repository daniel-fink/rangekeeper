"""Write the rename map table in the upgrade guide from rename_map.yaml.

Run `python -m tools.codemod.render` to update the guide, or add `--check` to
fail when the guide does not match the map.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
MAP = Path(__file__).with_name("rename_map.yaml")
GUIDE = ROOT / "docs" / "guides" / "upgrading.md"
START = "<!-- rename-map:start (generated by tools/codemod/render.py) -->"
END = "<!-- rename-map:end -->"


def _status(entry: Mapping) -> str:
    status = entry["status"]
    requires = entry.get("requires") or ()
    if requires:
        status += " (needs " + " and ".join(requires) + ")"
    return status


def _reason(entry: Mapping) -> str:
    text = entry.get("pending") or entry.get("note") or ""
    return " ".join(str(text).split()).replace("|", "\\|")


def _code(text: str) -> str:
    return f"`{text}`" if text else "—"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    lines = [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join("---" for _ in header) + " |",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def render(data: Mapping) -> str:
    """Return the Markdown for the rename map."""
    lines: list[str] = []
    lines += ["### Module moves", ""]
    lines += _table(
        ("Current", "1.0", "Status", "Notes"),
        [
            (_code(e["old"]), _code(e["new"]), _status(e), _reason(e))
            for e in data.get("modules") or ()
        ]
        + [
            (_code(e["old"] + "/"), _code(e["new"] + "/"), _status(e), _reason(e))
            for e in data.get("paths") or ()
        ],
    )
    rows = []
    for e in data.get("symbols") or ():
        new = e.get("new_name") or e["name"]
        target = f"{e['new_module']}.{new}" if e.get("new_module") else new
        if not (e.get("new_name") or e.get("new_module")):
            target = ""
        rows.append(
            (_code(f"{e['module']}.{e['name']}"), _code(target), _status(e), _reason(e))
        )
    for e in data.get("attributes") or ():
        owner = "" if e["owner"] == "*" else e["owner"] + "."
        note = _reason(e)
        if e.get("apply") == "review":
            note = ("Each use needs review. " + note).strip()
        rows.append(
            (_code(f"{owner}{e['name']}"), _code(e["new_name"]), _status(e), note)
        )
    for e in data.get("parameters") or ():
        owner = "Any call" if e["callable"] == "*" else f"`{e['callable']}`"
        rows.append(
            (
                f"{owner}: `{e['name']}=`",
                _code(e["new_name"] + "="),
                _status(e),
                _reason(e),
            )
        )
    lines += ["", "### Renamed names", ""]
    lines += _table(("Current", "1.0", "Status", "Notes"), rows)
    lines += ["", "### Removed names", ""]
    lines += _table(
        ("Current", "Use instead", "Status"),
        [
            (_code(e["name"]), " ".join(e["replacement"].split()), _status(e))
            for e in data.get("removed") or ()
        ],
    )
    lines += ["", "### Changes of API shape", ""]
    lines += [
        "These decisions change API shapes, not only names. The codemod does not apply",
        "them; the issues that the table names make the changes.",
        "",
    ]
    lines += _table(
        ("Topic", "1.0", "Source"),
        [
            (e["topic"], _reason(e), e.get("source") or "—")
            for e in data.get("notes") or ()
        ],
    )
    return "\n".join(lines) + "\n"


def update(text: str, table: str) -> str:
    """Replace the generated block in the guide."""
    if START not in text or END not in text:
        raise SystemExit(f"{GUIDE} has no {START} ... {END} block")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{table}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    """Write or check the generated block."""
    args = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    args.add_argument(
        "--check", action="store_true", help="Fail when the guide is out of date."
    )
    options = args.parse_args(argv)
    data = yaml.safe_load(MAP.read_text(encoding="utf-8"))
    text = GUIDE.read_text(encoding="utf-8")
    new = update(text, render(data))
    if options.check:
        if new != text:
            print(
                f"{GUIDE.relative_to(ROOT)} is out of date; run python -m tools.codemod.render"
            )
            return 1
        return 0
    GUIDE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
